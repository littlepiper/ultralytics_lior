import numpy as np
import cv2

def vis(image, infos, class_names):
    for info in infos:
        label, bbox, conf = info
        x1, y1, x2, y2 = bbox

        cls_id = class_names.index(label)
        color = (_COLORS[cls_id] * 255).astype(np.uint8).tolist()
        if conf is not None:
            text = '{}:{:.1f}%'.format(label, conf * 100)
        else:
            text = '{}'.format(label)

        txt_color = (0, 0, 0) if np.mean(_COLORS[cls_id]) > 0.5 else (255, 255, 255)
        txt_size = cv2.getTextSize(text, cv2.FONT_HERSHEY_SIMPLEX, 0.4, 1)[0]
        cv2.rectangle(image, (x1, y1), (x2, y2), color, 2)

        txt_bk_color = (_COLORS[cls_id] * 255 * 0.7).astype(np.uint8).tolist()
        txt_bk_x2 = x1 + txt_size[0]
        txt_bk_y2 = y1 - txt_size[1] - 2
        if txt_bk_x2 > image.shape[1]:
            txt_bk_x2 = image.shape[1]
            text = text[:len(text) - 1]
        if txt_bk_y2 < 0:
            txt_bk_y2 = 0
            y1 = y1 + txt_size[1] + 2

        cv2.rectangle(image, (x1, y1 - txt_size[1] - 2), (x1 + txt_size[0], y1), txt_bk_color, -1)
        cv2.putText(image, text, (x1, y1 - 2), cv2.FONT_HERSHEY_SIMPLEX, 0.4, txt_color, thickness=1, lineType=cv2.LINE_AA)

    return image


